def build(quiet=False):
    docs, ents, maps, ent_scan, facts = bi.build_core(quiet=True)
    n_thr = bx.write_threads(docs)
    n_sec, n_inl, n_box = bx.write_open(docs)
    bx.write_access(docs, ents, ent_scan)
    n_ev = bx.write_timeline(docs)
    real = [d for d in docs if not d.snapshot]
    conflicts = sum(1 for f, v in facts if len(v) > 1 and not f.get("expect_variety"))
    new, old, _ = run_checks(docs, ents, maps, ent_scan, facts)
    numbers = "\n".join([
        f"- {len(real)} files indexed; {sum(len(v) for v in maps[2].values()) + sum(len(v) for v in maps[3].values())} links between them.",
        f"- {n_thr} mail threads; {n_ev} timed events on the timeline.",
        f"- {n_sec} open-question sections, {n_inl} inline markers, {n_box} unchecked to-do items.",
        f"- {conflicts} tracked facts have more than one value (see FACTS.md).",
        f"- Canon checker: {len(new)} new problem(s), {len(old)} already known.",
    ])
    (META / "LOOKUP.md").write_text(LOOKUP.format(numbers=numbers), encoding="utf-8", newline="\n")
    build_master.main()
    if not quiet:
        print(f"built: {len(real)} files, {n_thr} threads, {n_ev} timed events, {n_sec} open sections; checker {len(new)} new / {len(old)} known")
    return docs, ents, maps, ent_scan, facts


# ----------------------------------------------------------------------------- checker

EOD_BAD = re.compile(r"Executioner of Despair|Envoy of Devotion|Subjugator|The Willbreaker|Willbreaker")
BRACKETED = re.compile(r"\[[^\]\n]*(?:Executioner of Despair|Envoy of Devotion|Subjugator|The Willbreaker|Willbreaker|Harmony)[^\]\n]*\]")
# These files define the alternative names, so the naming rule cannot apply to them.
NAME_DEFINERS = {"2.02", "2.15", "2.29", "2.51", "C-26"}
MOJI = ("â€", "â†", "Â°")


def key(kind, path, detail):
    return f"{kind}|{path}|{detail}"


def run_checks(docs, ents, maps, ent_scan, facts):
    """Returns (new, known, all) where each item is (key, message)."""
    by_id, by_path, out_see, out_text, inc, broken = maps
    found = []
    real = [d for d in docs if not d.snapshot and d.path not in bi.GENERATED]
    for d in real:
        # 1 encoding damage
        if d.path != "meta/HANDOFF_CARTOGRAPHER.md" and any(m in d.text for m in MOJI):
            found.append((key("encoding", d.path, ""), f"{d.path}: damaged characters (run tools/fix_encoding.py)"))
        # 2 naming rule
        if d.path.startswith(("canon/", "story/")) and d.id not in NAME_DEFINERS:
            for n, line in enumerate(d.text.splitlines(), 1):
                if EOD_BAD.search(line):
                    rest = BRACKETED.sub("", line)
                    if EOD_BAD.search(rest) and not re.search(r"ARM-27|Subjugator (?:rifle|unit|array|module|equipment)", line):
                        found.append((key("naming", d.path, EOD_BAD.search(rest).group(0)), f"{d.path}:{n}: alternative EOD name outside square brackets"))
        # 3 broken references
        for b in sorted(broken.get(d.path, ())):
            found.append((key("broken-ref", d.path, b), f"{d.path}: points at {b}, which is not a file in the repo"))
        # 4 mail headers
        if bx.is_mail(d):
            fh, msgs = bx.parse_messages(d)
            if not msgs:
                found.append((key("mail-header", d.path, "From"), f"{d.path}: no **From:** line"))
            for i, m in enumerate(msgs, 1):
                for k in ("To", "Subject"):
                    if not (m.get(k) or fh.get(k)):
                        found.append((key("mail-header", d.path, f"{k}{i}"), f"{d.path}: message {i} has no **{k}:** line"))
        # 5 proposal not tagged in new files is not detectable; unsent drafts are reported by flags
    # 6 duplicate ids
    seen = collections.defaultdict(list)
    for d in real:
        if d.id:
            seen[d.id].append(d.path)
    for i, ps in seen.items():
        if len(ps) > 1:
            found.append((key("duplicate-id", i, ""), f"id {i} is used by {len(ps)} files: {', '.join(ps)}"))
    # 7 fact conflicts
    for f, vals in facts:
        if len(vals) > 1 and not f.get("expect_variety"):
            found.append((key("fact", f["name"], "|".join(sorted(vals))),
                          f"fact “{f['name']}” has {len(vals)} values: " + "; ".join(f"{v} ({len(l)}×)" for v, l in vals.items())))
    # 8 restricted names below their level
    rules = bx.load_json("access_rules.json")
    scope = tuple(rules["in_world_sources"])
    for term in rules["terms"]:
        rx, minr = re.compile(term["pattern"]), rules["tiers"][term["min"]]
        for d in real:
            if d.path.startswith(scope) and d.p.name != "README.md" and rules["tiers"].get(d.access, 99) < minr and rx.search(d.text):
                found.append((key("access", d.path, term["name"]), f"{d.path} ({d.access}) mentions “{term['name']}”, minimum level {term['min']}"))
    seen_keys, uniq = set(), []
    for k, m in found:
        if k not in seen_keys:
            seen_keys.add(k)
            uniq.append((k, m))
    base = set(json.loads(BASELINE.read_text(encoding="utf-8"))["known"]) if BASELINE.exists() else set()
    new = [x for x in uniq if x[0] not in base]
    old = [x for x in uniq if x[0] in base]
    return new, old, uniq


def cmd_check(a):
    docs = bi.load()
    ents = bi.compile_entities(bx.load_json("entities.json"))
    maps = bi.scan_links(docs)
    ent_scan = bi.scan_entities(docs, ents)
    facts = bi.scan_facts(docs, bx.load_json("facts.json"))
    new, old, allp = run_checks(docs, ents, maps, ent_scan, facts)
    if a.accept:
        BASELINE.write_text(json.dumps({"_help": "Problems a person has looked at and accepted for now. `ics.py check` fails only on problems not listed. "
                                        "Delete a line when you fix the problem; re-create with `ics.py check --accept`.",
                                        "known": sorted(k for k, _ in allp)}, indent=1), encoding="utf-8", newline="\n")
        print(f"baseline saved: {len(allp)} known problems")
        return 0
    show = allp if a.all else new
    by = collections.defaultdict(list)
    for k, m in show:
        by[k.split("|")[0]].append(m)
    for kind, msgs in sorted(by.items()):
        print(f"\n== {kind} ({len(msgs)})")
        for m in msgs[:60]:
            print("  " + m)
        if len(msgs) > 60:
            print(f"  … {len(msgs) - 60} more")
    print(f"\n{len(new)} new problem(s); {len(old)} already known" + ("" if new else ". Clean."))
    return 1 if new else 0


# ----------------------------------------------------------------------------- hooks, quick

def newest(paths):
    return max((p.stat().st_mtime for p in paths if p.exists()), default=0)


def cmd_quick():
    src = [p for p in bi.all_md() if bi.rel(p) not in bi.GENERATED and bi.rel(p) not in bi.SNAPSHOTS]
    src += list((ROOT / "tools").glob("*.json"))
    gen = [ROOT / g for g in GEN]
    if newest(src) <= min((p.stat().st_mtime for p in gen if p.exists()), default=0) and all(p.exists() for p in gen):
        print("generated files are up to date")
        return 0
    build()
    return 0


HOOK = """#!/bin/sh
# Installed by `python3 tools/ics.py install-hooks`. Rebuilds the generated files and adds them to the commit.
# Skip once with:  ICS_NO_REBUILD=1 git commit ...
[ -n "$ICS_NO_REBUILD" ] && exit 0
cd "$(git rev-parse --show-toplevel)" || exit 0
PY=$(command -v python3 || command -v python)
[ -z "$PY" ] && exit 0
if git diff --cached --name-only | grep -qE '\\.(md|json)$'; then
  "$PY" tools/ics.py build >/dev/null 2>&1 || {{ echo "ics: rebuild failed; commit continues without it"; exit 0; }}
  git add meta/INDEX.md meta/ENTITIES.md meta/LINKS.md meta/FACTS.md meta/graph.html meta/THREADS.md meta/OPEN.md \\
          meta/ACCESS.md meta/TIMELINE.md meta/LOOKUP.md reference/ICS_Rigged_Sphere_MASTER_REFERENCE.md 2>/dev/null
  "$PY" tools/ics.py check || echo "ics: the canon checker found NEW problems above (commit continues; fix or accept them)"
fi
exit 0
"""


def cmd_install():
    hooks = ROOT / "tools" / "hooks"
    hooks.mkdir(exist_ok=True)
    (hooks / "pre-commit").write_text(HOOK.format(), encoding="utf-8", newline="\n")
    (hooks / "pre-commit").chmod(0o755)
    r = subprocess.run(["git", "config", "core.hooksPath", "tools/hooks"], cwd=ROOT, capture_output=True, text=True)
    if r.returncode:
        print("git config failed:", r.stderr.strip())
        return 1
    print("installed: git will now use tools/hooks. Every commit that touches .md or .json files rebuilds the generated files and adds them.")
    print("skip once with  ICS_NO_REBUILD=1 git commit ...")
    return 0


def cmd_impact(q):
    docs = bi.load()
    ents = bi.compile_entities(bx.load_json("entities.json"))
    maps = bi.scan_links(docs)
    ent_scan = bi.scan_entities(docs, ents)
    facts = bi.scan_facts(docs, bx.load_json("facts.json"))
    bx.impact(docs, ents, maps, ent_scan, facts, q)
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["build", "check", "impact", "who", "install-hooks", "quick"])
    ap.add_argument("arg", nargs="?")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--accept", action="store_true")
    a = ap.parse_args()
    if a.cmd == "build":
        build()
    elif a.cmd == "check":
        return cmd_check(a)
    elif a.cmd == "impact" and a.arg:
        return cmd_impact(a.arg)
    elif a.cmd == "who" and a.arg:
        return bi.cli_who(bi.load(), bi.compile_entities(bx.load_json("entities.json")), a.arg)
    elif a.cmd == "install-hooks":
        return cmd_install()
    elif a.cmd == "quick":
        return cmd_quick()
    else:
        ap.error("this command needs an argument")


if __name__ == "__main__":
    sys.exit(main())
