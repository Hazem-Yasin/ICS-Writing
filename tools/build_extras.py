#!/usr/bin/env python3
"""Second set of generated reading aids, built on the parsers in build_index.py.

Writes into meta/:
  THREADS.md   mail grouped into conversations, and who writes to whom
  OPEN.md      every open question, open ruling, TODO and unchecked to-do item, in one place
  ACCESS.md    who can read what; where a restricted name appears below its level
  TIMELINE.md  every "Day N" (with the time, when one is given) in order

Run everything with:  python3 tools/ics.py build
Impact check:         python3 tools/ics.py impact C-24
"""
import collections
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_index as bi  # noqa: E402

ROOT, META = bi.ROOT, bi.META
HEADER = ("*Generated by `tools/build_extras.py` (run `python3 tools/ics.py build`). Do not edit by hand; "
          "it is overwritten on every build.*")


def load_json(name):
    return json.loads((ROOT / "tools" / name).read_text(encoding="utf-8"))


def put(name, lines):
    (META / name).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def cut(s, n):
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


# ----------------------------------------------------------------------------- mail parsing

HDR = re.compile(r"^\*\*(From|To|Cc|Subject|Date|Status):\*\*\s*(.*)$")
ADDR = re.compile(r"\s*<[^>]*>")
TAG_RE = re.compile(r"Deployment Order \d+|ICS-IR3-[\w-]+|E-\d{5}")


def is_mail(d):
    return d.path.startswith("canon/internal-communications/") and d.p.name != "README.md"


def parse_messages(d):
    """Returns (file-level headers, [message dicts]). A message starts at a From line."""
    file_hdr, msgs, cur = {}, [], None
    for n, line in enumerate(d.text.splitlines(), 1):
        m = HDR.match(line.strip())
        if not m:
            continue
        k, v = m.group(1), bi.clean(ADDR.sub("", m.group(2)))
        if k == "From":
            cur = {"From": v, "line": n}
            msgs.append(cur)
        elif cur is None:
            file_hdr.setdefault(k, v)
        else:
            cur.setdefault(k, v)
    return file_hdr, msgs


def norm_subject(s):
    s = s.lower().replace("[as sent]", "")
    while True:
        n = re.sub(r"^\s*(re|fwd?|fw)\s*:\s*", "", s)
        if n == s:
            break
        s = n
    s = re.sub(r"[^a-z0-9]+", " ", s).strip()
    return "" if s.startswith(("no subject", "none")) else s


def strip_re(s):
    return re.sub(r"^\s*((re|fwd?|fw)\s*:\s*)+", "", s, flags=re.I)


def day_key(date):
    m = re.search(r"Day (\d+)(?:,\s*(\d\d):(\d\d))?", date or "")
    if not m:
        return None
    return int(m.group(1)), (int(m.group(2)) * 60 + int(m.group(3))) if m.group(2) else None


def party(s):
    s = re.split(r"\s*[(\[]", s)[0].strip()
    return cut(s, 40) or "?"


def find_threads(docs):
    mails = [d for d in docs if is_mail(d)]
    cfg = load_json("threads.json")["threads"]
    parent = {d.path: d.path for d in mails}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a, b):
        parent[find(a)] = find(b)

    info, keys = {}, collections.defaultdict(set)
    for d in mails:
        fh, msgs = parse_messages(d)
        info[d.path] = (fh, msgs)
        subs = {fh.get("Subject", "")} | {m.get("Subject", "") for m in msgs}
        for s in subs:
            k = norm_subject(s)
            if len(k) > 3:
                keys["s:" + k].add(d.path)
            for t in TAG_RE.findall(s):
                keys["t:" + t].add(d.path)
    for paths in keys.values():
        paths = sorted(paths)
        for p in paths[1:]:
            union(paths[0], p)

    manual = {}
    for entry in cfg:
        paths = []
        for tok in entry["files"]:
            hit = [d.path for d in mails if (d.id and d.id.lower() == tok.lower()) or d.p.name.lower().startswith(tok.lower())]
            paths += hit[:1]
        for p in paths[1:]:
            union(paths[0], p)
        if paths:
            manual[paths[0]] = entry["name"]

    comps = collections.defaultdict(list)
    for d in mails:
        comps[find(d.path)].append(d)
    out = []
    by_path = {d.path: d for d in mails}
    for root, files in comps.items():
        files.sort(key=lambda d: (d.id or d.p.name))
        nmsg = sum(max(1, len(info[d.path][1])) for d in files)
        if len(files) < 2 and nmsg < 2:
            continue
        name = next((manual[p] for p in manual if find(p) == root), None)
        how = "listed by hand in tools/threads.json" if name else "matched by subject or tag"
        if not name:
            fh, msgs = info[files[0].path]
            name = strip_re((msgs[0].get("Subject") if msgs else None) or fh.get("Subject", "") or files[0].title)
        out.append((name, how, files))
    out.sort(key=lambda t: (t[2][0].id or t[2][0].p.name))
    singles = len(mails) - sum(len(f) for _, _, f in out)
    return out, info, singles


def write_threads(docs):
    threads, info, singles = find_threads(docs)
    lines = ["# Mail threads", "", HEADER, "",
             "Messages grouped into conversations. A thread is found when files share a subject once Re:/Fwd: are removed, or share a tag in the "
             "subject (Deployment Order 287, E-03615, ICS-IR3-…). Anything the subjects do not reveal is listed by hand in `tools/threads.json`. "
             "A file holding several messages (B-28, C-26) counts as a thread by itself. Order is by id, which is not always date order: check the Date column.", "",
             f"**{len(threads)} threads. {singles} messages stand alone** (see `meta/INDEX.md`).", ""]
    for name, how, files in threads:
        n = sum(max(1, len(info[d.path][1])) for d in files)
        lines += [f"## {cut(name, 110)}", "", f"*{len(files)} file{'s' if len(files) != 1 else ''}, {n} messages. {how}.*", "",
                  "| File | Date | From → To | Subject | Access |", "|---|---|---|---|---|"]
        for d in files:
            fh, msgs = info[d.path]
            for m in (msgs or [{"From": "?", "To": "?"}]):
                date = m.get("Date") or fh.get("Date", "—")
                sub = m.get("Subject") or fh.get("Subject", "—")
                lines.append(f"| {bi.md_link(d)} | {cut(date, 40)} | {party(m.get('From', '?'))} → {party(m.get('To', '?'))} | "
                             f"{cut(sub, 70).replace('|', '/')} | {d.access} |")
        lines.append("")
    pairs = collections.Counter()
    for d in docs:
        if not is_mail(d):
            continue
        for m in info.get(d.path, ({}, []))[1] if d.path in info else parse_messages(d)[1]:
            for to in re.split(r"[;,]", m.get("To", "")):
                if to.strip():
                    pairs[(party(m["From"]), party(to))] += 1
    lines += ["## Who writes to whom", "", "Counts of messages by sender and recipient (the To line only).", "",
              "| Messages | From | To |", "|---|---|---|"]
    lines += [f"| {n} | {a} | {b} |" for (a, b), n in pairs.most_common(25)]
    put("THREADS.md", lines)
    return len(threads)


# ----------------------------------------------------------------------------- open items

HEAD_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*$")
OPEN_TITLE = re.compile(r"\bopen (questions?|rulings?|points?|items?)\b|\bunresolved\b|\bloose ends\b|\bTBD\b|^\W*open\W*$", re.I)
INLINE = re.compile(r"\bTODO\b|\bTBD\b|\[OPEN\]|[Tt]o be (?:decided|confirmed|ruled)|[Nn]eeds? a ruling|[Nn]ot yet decided")
BOX = re.compile(r"^\s*[-*]\s*\[ \]\s*(.*)$")


def open_sections(d):
    lines = d.text.splitlines()
    found, i = [], 0
    while i < len(lines):
        m = HEAD_RE.match(lines[i])
        if m and OPEN_TITLE.search(m.group(2)):
            lvl, j = len(m.group(1)), i + 1
            while j < len(lines):
                h = HEAD_RE.match(lines[j])
                if h and len(h.group(1)) <= lvl:
                    break
                j += 1
            body = [l.rstrip() for l in lines[i + 1:j] if l.strip() and l.strip() != "---"]
            found.append((i + 1, m.group(2), body))
            i = j
        else:
            i += 1
    return found


def write_open(docs):
    real = [d for d in docs if not d.snapshot]
    todo = next((d for d in real if d.path == "meta/TODO.md"), None)
    lines = ["# Open questions and unfinished work", "", HEADER, "",
             "Everything the repo itself marks as undecided or unfinished: sections headed *Open questions / Open rulings / Open points*, "
             "inline TODO/TBD/“to be decided” markers, and the unchecked items in `meta/TODO.md`. Nothing here is new; it is gathered. "
             "Rulings belong to the author: this page does not decide any of them.", ""]
    area = collections.defaultdict(list)
    n_sec = n_items = 0
    inl = []
    for d in real:
        if d.path == "meta/TODO.md":
            continue
        secs = open_sections(d)
        covered = set()
        for ln, title, body in secs:
            area[d.path.split("/")[0]].append((d, ln, title, body))
            n_sec += 1
            n_items += len([b for b in body if re.match(r"^\s*(\d+\.|[-*])\s", b) and not re.match(r"^\s{2,}", b)])
            covered.update(range(ln, ln + len(body) + 6))
        for n, l in enumerate(d.text.splitlines(), 1):
            if n in covered or l.strip().startswith(("|", "```")):
                continue
            if INLINE.search(l):
                inl.append((d, n, l))
    boxes = []
    if todo:
        sec = ""
        for n, l in enumerate(todo.text.splitlines(), 1):
            h = HEAD_RE.match(l)
            if h and len(h.group(1)) == 2:
                sec = h.group(2)
            m = BOX.match(l)
            if m:
                boxes.append((sec, n, m.group(1)))
    prop = [d for d in real if "proposal" in d.flags and d.path.startswith(("canon/", "story/", "design/"))]
    lines += ["| What | Count |", "|---|---|",
              f"| Open-question sections | {n_sec} (about {n_items} listed items) |",
              f"| Inline TODO / TBD / “to be decided” lines | {len(inl)} |",
              f"| Unchecked items in `meta/TODO.md` | {len(boxes)} |",
              f"| Files carrying [PROPOSAL] material not yet ruled canon | {len(prop)} |", ""]
    if boxes:
        lines += ["## The author's to-do list (`meta/TODO.md`)", ""]
        last = None
        for sec, n, t in boxes:
            if sec != last:
                lines += [f"**{sec}**", ""]
                last = sec
            lines.append(f"- {cut(bi.clean(t) if False else re.sub(r'[*]+', '', t), 300)} *(line {n})*")
        lines.append("")
    names = {"canon": "Canon files", "design": "Design files", "story": "Story files", "meta": "Meta files", "README.md": "README"}
    for a in ("meta", "design", "canon", "story", "README.md"):
        if not area.get(a):
            continue
        lines += [f"## {names[a]}: open sections", ""]
        for d, ln, title, body in sorted(area[a], key=lambda x: x[0].path):
            lines += [f"### {md_title(d)} — “{cut(title, 80)}”", "", f"`{d.path}` line {ln}", ""]
            shown = body[:45]
            for b in shown:
                t = re.sub(r"^(\s*)(\d+\.|[-*])\s+", lambda m: m.group(1) + "- ", b)
                lines.append(cut(t, 420) if not t.startswith(" ") else "  " + cut(t.strip(), 420))
            if len(body) > len(shown):
                lines.append(f"- … {len(body) - len(shown)} more lines in the file")
            lines.append("")
    if inl:
        lines += ["## Inline markers", "", "| File | Line | Text |", "|---|---|---|"]
        for d, n, l in sorted(inl, key=lambda x: (x[0].path, x[1])):
            lines.append(f"| {bi.md_link(d)} | {n} | {cut(bi.clean(l), 160).replace('|', '/')} |")
        lines.append("")
    lines += ["## Files carrying [PROPOSAL] material", "",
              "These contain new material that stays proposal until the author rules. Listed so none are forgotten.", ""]
    lines += [f"- {bi.md_link(d)} {cut(d.title, 70)}" for d in sorted(prop, key=lambda x: x.path)]
    put("OPEN.md", lines)
    return n_sec, len(inl), len(boxes)


def md_title(d):
    return f"{d.label}: {cut(d.title, 60)}" if d.id else cut(d.title, 70)


# ----------------------------------------------------------------------------- access

def write_access(docs, ents, ent_scan):
    rules = load_json("access_rules.json")
    tiers = rules["tiers"]
    scope = tuple(rules["in_world_sources"])
    lines = ["# Who can read what", "", HEADER, "",
             "The access level of each file is read from its header (Status / Classification / Access lines). The README's rule: Global Access (everyone), "
             "PTKW Access (mid-level management), Board Access (the deepest layer). Sealed files name their readers. Levels: "
             + ", ".join(f"{k} = {v}" for k, v in tiers.items()) + ". “—” means the file states no level.", ""]
    real = [d for d in docs if not d.snapshot]
    labels = ["Employee", "Global", "PTKW", "Branch Director", "Above Director", "Board", "Sealed", "—"]
    secs = sorted({d.section for d in real if d.section.startswith("canon")})
    lines += ["## Files by section and level", "", "| Section | " + " | ".join(labels) + " |", "|---|" + "---|" * len(labels)]
    for s in secs:
        c = collections.Counter(d.access for d in real if d.section == s)
        lines.append(f"| `{s}` | " + " | ".join(str(c.get(l, 0)) or "" for l in labels) + " |")
    lines.append("")

    lines += ["## Who can know about each thing", "",
              "For each tracked entity, how many files at each level mention it. A thing that appears in Employee or Global files is something "
              "ordinary staff could have read. Counts are text matches (see `meta/ENTITIES.md` for the limits).", "",
              "| Entity | " + " | ".join(labels) + " |", "|---|" + "---|" * len(labels)]
    by_path = {d.path: d for d in real}
    for e, _ in ents:
        c = collections.Counter(by_path[p].access for p in ent_scan[e["name"]] if p in by_path and by_path[p].path.startswith("canon/"))
        if c:
            lines.append(f"| {e['name']} | " + " | ".join(str(c.get(l, "")) for l in labels) + " |")
    lines.append("")

    lines += ["## Restricted names found below their level", "",
              "Each rule in `tools/access_rules.json` names a term and the lowest level that should mention it. Only in-world files are checked "
              "(documents, mail, weapons, facility, enemies). A hit is not always an error: a *See* line pointing at a restricted document, or "
              "a fictional character who does know, can be fine. Check the line before acting. Files that state no level are listed separately.", ""]
    for term in rules["terms"]:
        rx = re.compile(term["pattern"])
        minr = tiers[term["min"]]
        bad, unk = [], []
        for d in real:
            if not d.path.startswith(scope) or d.p.name == "README.md":
                continue
            hits = [(n, l) for n, l in enumerate(d.text.splitlines(), 1) if rx.search(l)]
            if not hits:
                continue
            r = tiers.get(d.access)
            if r is None:
                unk.append((d, hits))
            elif r < minr:
                bad.append((d, hits))
        lines += [f"### {term['name']}", "", f"*Minimum level: {term['min']}. {term['note']}*", ""]
        if not bad:
            lines.append("None below the level.")
        else:
            lines += ["| File | Level | Hits | First hit |", "|---|---|---|---|"]
            for d, hits in sorted(bad, key=lambda x: x[0].path):
                n, l = hits[0]
                lines.append(f"| {bi.md_link(d)} | {d.access} | {len(hits)} | line {n}: {cut(bi.clean(l), 110).replace('|', '/')} |")
        if unk:
            lines += ["", f"No level stated, mentions it: " + ", ".join(f"{bi.md_link(d)} ({len(h)})" for d, h in sorted(unk, key=lambda x: x[0].path))]
        lines.append("")
    nolevel = [d for d in real if d.path.startswith(scope) and d.access == "—" and d.p.name != "README.md"]
    lines += ["## In-world files that state no level", "",
              f"{len(nolevel)} files. Some are deliberately unclassified (Doc 2.39 says it has no level). The rest could be given one.", ""]
    lines += [f"- {bi.md_link(d)} {cut(d.title, 70)}" for d in sorted(nolevel, key=lambda x: x.path)]
    put("ACCESS.md", lines)


# ----------------------------------------------------------------------------- timeline

DAY_RE = re.compile(r"\bDay (\d{1,3})\b(?:\s*[,—–-]?\s*(?:at |about |around |~)?((?:[01]?\d|2[0-4]):[0-5]\d)(?!\d))?")
OTHER_CYCLE = re.compile(r"Cycle (?!300\b)\d+")


def write_timeline(docs):
    events, untimed, design = [], collections.defaultdict(collections.Counter), collections.Counter()
    skipped = []
    for d in docs:
        if d.snapshot or not d.path.startswith(("canon/", "story/", "design/")):
            continue
        dm = re.search(r"^\*\*Date:\*\*\s*(.+)$", d.text, re.M)
        if dm and re.search(r"Cycle (?!300\b)\d+", dm.group(1)):
            skipped.append(d)
            continue
        subject = parse_messages(d)[0].get("Subject") or d.title
        for n, l in enumerate(d.text.splitlines(), 1):
            if OTHER_CYCLE.search(l):
                continue
            for m in DAY_RE.finditer(l):
                day, t = int(m.group(1)), m.group(2)
                if d.path.startswith("design/"):
                    design[day] += 1
                    continue
                if l.lstrip().startswith("**Date:**"):
                    snippet = "mail sent: " + cut(subject, 110)
                else:
                    s = max(0, m.start() - 60)
                    snippet = cut(bi.clean(l[s: m.end() + 110]), 170)
                if t:
                    events.append((day, int(t[:-3]) * 60 + int(t[-2:]), t, d, n, snippet))
                else:
                    untimed[day][d.path] += 1
    days = sorted({e[0] for e in events} | set(untimed))
    by_day = collections.defaultdict(list)
    for e in sorted(events, key=lambda e: (e[0], e[1], e[3].path, e[4])):
        by_day[e[0]].append(e)
    paths = {d.path: d for d in docs}
    lines = ["# Timeline: every “Day N”", "", HEADER, "",
             "Every “Day N” in the canon and story files, with the clock time when one follows it on the same line (Cycle 300 Q4 is one calendar). "
             "Times in the *Time* column are as written in each source, which does not always say whose clock. Lines that name another Cycle are left out, "
             f"and so are {len(skipped)} files whose Date header names another Cycle ({', '.join(d.label for d in skipped) or 'none'}). "
             "Mentions in `design/` are only counted. Not caught: times with no “Day” on the same line (C-21’s “scramble 02:44”) and ranges (“Days 11 to 20”).", "",
             "| Day | Timed | Untimed mentions | Design mentions |", "|---|---|---|---|"]
    for day in days:
        lines.append(f"| [{day}](#day-{day}) | {len(by_day.get(day, []))} | {sum(untimed.get(day, {}).values())} | {design.get(day, 0)} |")
    lines.append("")
    for day in days:
        lines += [f"## Day {day}", ""]
        if by_day.get(day):
            lines += ["| Time | File | Line | What it says |", "|---|---|---|---|"]
            for _, _, t, d, n, sn in by_day[day]:
                lines.append(f"| {t} | {bi.md_link(d)} | {n} | {sn.replace('|', '/')} |")
            lines.append("")
        if untimed.get(day):
            lines.append("No time given: " + ", ".join(f"{paths[p].label} ×{c}" if c > 1 else paths[p].label
                                                       for p, c in sorted(untimed[day].items())))
            lines.append("")
    put("TIMELINE.md", lines)
    return len(events)


# ----------------------------------------------------------------------------- impact check

def impact(docs, ents, maps, ent_scan, facts, q):
    by_id, by_path, out_see, out_text, inc, broken = maps
    ql = q.lower()
    hits = [d for d in docs if not d.snapshot and ((d.id and d.id.lower() == ql) or ql in d.path.lower())]
    if not hits:
        print(f"No file matches {q!r}.")
        return
    threads, info, _ = find_threads(docs)
    for d in hits[:3]:
        print(f"\n{d.path}\n  {d.title}   [{d.access}]")
        cites = sorted(inc.get(d.path, ()))
        see_in = [p for p in cites if d.path in out_see[p]]
        txt_in = [p for p in cites if p not in see_in]
        lab = lambda p: by_path[p].label  # noqa: E731
        print(f"\n  Files that point at it ({len(cites)}): check these if you change it")
        print("    See links :", ", ".join(map(lab, see_in)) or "-")
        print("    Text only :", ", ".join(map(lab, txt_in)) or "-")
        print("  It points at:", ", ".join(lab(p) for p in sorted(out_see[d.path] | out_text[d.path])) or "-")
        mine = [(e["name"], sum(ent_scan[e["name"]][d.path].values())) for e, _ in ents if d.path in ent_scan[e["name"]]]
        print("\n  Entities in it:", ", ".join(f"{n} ×{c}" for n, c in sorted(mine, key=lambda x: -x[1])[:12]) or "-")
        shared = collections.Counter()
        for name, _ in mine:
            for p in ent_scan[name]:
                if p != d.path and not by_path[p].snapshot:
                    shared[p] += 1
        print("  Files sharing most entities:", ", ".join(f"{lab(p)}({c})" for p, c in shared.most_common(8)) or "-")
        any_fact = False
        for f, vals in facts:
            here = [(v, ln) for v, locs in vals.items() for p, ln, _ in locs if p == d.path]
            if not here:
                continue
            any_fact = True
            others = collections.defaultdict(set)
            for v, locs in vals.items():
                for p, ln, _ in locs:
                    if p != d.path:
                        others[v].add(lab(p))
            for v, ln in here:
                print(f"  Fact “{f['name']}” = {v} (line {ln}); also: " + ("; ".join(f"{ov}: {', '.join(sorted(ps)[:5])}" for ov, ps in others.items()) or "nowhere else"))
        if not any_fact:
            print("  Facts tracked in it: none")
        for name, how, files in threads:
            if d in files:
                print(f"\n  Mail thread “{cut(name, 70)}”: " + ", ".join(f.label for f in files))
        print()
